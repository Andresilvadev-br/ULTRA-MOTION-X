/**
 * Integration planner. Produces an explicit list of file changes (computed in memory) that
 * can be reviewed as a diff (`--dry-run`) before anything is written.
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import type { ProjectReport } from "./analyzer.ts";
import type { UmxSource } from "./source.ts";
import { exists, readJson, readText, toPosix } from "./util.ts";

export type ChangeKind = "create" | "modify" | "json";

export interface PlannedChange {
  kind: ChangeKind;
  path: string;
  description: string;
  /** Text or bytes after the change. */
  after: string | Buffer;
  /** Current content (null when the file does not exist yet). */
  before: string | Buffer | null;
  /** For `json` changes: the key path that was added/changed and its previous value. */
  json?: { pointer: string[]; value: unknown; previous: unknown };
}

export interface IntegrationConfig {
  $schema?: string;
  profile: string;
  reducedMotion: "user" | "always" | "never";
  fidelity: { min: number; max: number; initial: number };
  compositor: "auto" | "always" | "never";
  enhance: { roles: string[]; lists: boolean };
  /** Optional MDL document with custom components/timelines. */
  motion?: string;
}

export interface PlanOptions {
  mode?: "vendor" | "npm";
  profile?: string;
  annotate?: boolean;
  entry?: string;
  adapter?: string;
  roles?: string[];
  buildNative?: boolean;
}

export interface IntegrationPlan {
  root: string;
  adapter: string;
  mode: "vendor" | "npm";
  version: string;
  changes: PlannedChange[];
  notes: string[];
  manualSteps: string[];
}

export const CONFIG_FILE = "ultra-motion.config.json";
export const VENDOR_DIR = "vendor/ultra-motion-x";
export const DEFAULT_ROLES = [
  "button",
  "card",
  "menu",
  "modal",
  "drawer",
  "notification",
  "tooltip",
  "navigation",
  "list",
  "disclosure",
];

export function defaultConfig(profile = "professional", roles = DEFAULT_ROLES): IntegrationConfig {
  return {
    $schema: "./vendor/ultra-motion-x/schema/config.schema.json",
    profile,
    reducedMotion: "user",
    fidelity: { min: 0, max: 4, initial: 3 },
    compositor: "auto",
    enhance: { roles, lists: true },
  };
}

/** Text of the generated web bootstrap module. */
export function bootstrapSource(config: IntegrationConfig, importPath: string, ts: boolean): string {
  const cfg = JSON.stringify(
    {
      profile: config.profile,
      reducedMotion: config.reducedMotion,
      fidelity: config.fidelity,
      compositor: config.compositor,
      enhance: config.enhance,
    },
    null,
    2,
  );
  return `// Generated by Ultra Motion X (umx install). Regenerate with \`umx config apply\`.
// Source of truth: ${CONFIG_FILE}. Safe to import on the server: it only runs in browsers.
import { autoEnhance, configureEngine } from "${importPath}";

const config = ${cfg}${ts ? " as const" : ""};

if (typeof window !== "undefined" && typeof document !== "undefined") {
  const engine = configureEngine({
    profile: config.profile${ts ? " as never" : ""},
    reducedMotion: config.reducedMotion,
    compositor: config.compositor,
    fidelity: { min: config.fidelity.min${ts ? " as 0" : ""}, max: config.fidelity.max${ts ? " as 4" : ""}, initial: config.fidelity.initial${ts ? " as 3" : ""} },
  });
  engine.dna.applyCssVariables();
  const start = () => autoEnhance({ engine, roles: [...config.enhance.roles]${ts ? " as never" : ""}, lists: config.enhance.lists });
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start, { once: true });
  else start();
}
`;
}

function listFiles(dir: string): string[] {
  const out: string[] = [];
  const rec = (d: string) => {
    for (const n of readdirSync(d)) {
      const f = join(d, n);
      if (statSync(f).isDirectory()) rec(f);
      else out.push(f);
    }
  };
  if (exists(dir)) rec(dir);
  return out.sort();
}

function copyTree(
  src: string,
  destRel: string,
  root: string,
  description: string,
  filter: (f: string) => boolean = () => true,
): PlannedChange[] {
  return listFiles(src)
    .filter(filter)
    .map((f) => {
      const path = toPosix(join(destRel, relative(src, f)));
      const full = join(root, path);
      return {
        kind: "create" as const,
        path,
        description,
        after: readFileSync(f),
        before: exists(full) ? readFileSync(full) : null,
      };
    });
}

function injectImport(text: string, spec: string): string {
  const line = `import "${spec}";`;
  if (text.includes(line)) return text;
  const lines = text.split("\n");
  let last = -1;
  let directive = -1;
  lines.forEach((l, i) => {
    if (/^\s*import\b.*(from\s+)?["'][^"']+["'];?\s*$/.test(l)) last = i;
    if (/^\s*["']use (client|strict)["'];?\s*$/.test(l) && i < 3) directive = i;
  });
  const at = last >= 0 ? last + 1 : directive + 1;
  lines.splice(at, 0, line);
  return lines.join("\n");
}

function injectScript(html: string, src: string): string {
  const tag = `<script type="module" src="${src}"></script>`;
  if (html.includes(tag)) return html;
  return /<\/body>/i.test(html) ? html.replace(/<\/body>/i, `  ${tag}\n</body>`) : `${html}\n${tag}\n`;
}

const ANNOTATIONS: Array<[RegExp, string]> = [
  [/\b(?:class|className)=["'][^"']*\b(?:card|tile)\b[^"']*["']/, "card"],
  [/\b(?:class|className)=["'][^"']*\b(?:toast|snackbar|notification)\b[^"']*["']/, "notification"],
  [/\b(?:class|className)=["'][^"']*\b(?:drawer|offcanvas)\b[^"']*["']/, "drawer"],
  [/\b(?:class|className)=["'][^"']*\bmodal\b[^"']*["']/, "modal"],
  [/\b(?:class|className)=["'][^"']*\b(?:dropdown|menu)\b[^"']*["']/, "menu"],
];

/** Adds `data-umx="<role>"` to opening tags with unambiguous class names. */
export function annotateSource(text: string): { text: string; count: number } {
  let count = 0;
  const out = text.replace(
    /<([a-zA-Z][\w.-]*)(\s[^<>]*?)(\/?)>/g,
    (full, tag: string, attrs: string, selfClose: string) => {
      if (/\bdata-umx=/.test(attrs) || /^[A-Z]/.test(tag)) return full;
      for (const [re, role] of ANNOTATIONS) {
        if (re.test(attrs)) {
          count++;
          return `<${tag}${attrs} data-umx="${role}"${selfClose}>`;
        }
      }
      return full;
    },
  );
  return { text: out, count };
}

export function createPlan(report: ProjectReport, source: UmxSource, opts: PlanOptions = {}): IntegrationPlan {
  const root = report.root;
  const adapter = opts.adapter ?? report.adapter;
  const mode = opts.mode ?? "vendor";
  const changes: PlannedChange[] = [];
  const notes: string[] = [];
  const manualSteps: string[] = [];
  const add = (c: PlannedChange) => changes.push(c);
  const textFile = (p: string) => readText(join(root, p));

  const webLike =
    ["web", "react", "vue", "svelte", "angular", "electron", "tauri"].includes(adapter) ||
    report.platform === "web" ||
    report.platform === "electron" ||
    report.platform === "tauri";
  if (webLike) {
    const config = defaultConfig(opts.profile ?? "professional", opts.roles);
    if (!exists(join(root, CONFIG_FILE)))
      add({
        kind: "create",
        path: CONFIG_FILE,
        description: "Motion configuration (profile, accessibility, fidelity, auto-enhance roles)",
        after: `${JSON.stringify(config, null, 2)}\n`,
        before: null,
      });
    else notes.push(`${CONFIG_FILE} already exists and was kept.`);
    const hasPkg = exists(join(root, "package.json"));
    if (!exists(source.webDist))
      throw new Error(`Web SDK is not built (${source.webDist} missing). Run \`npm run build\` in ${source.root}.`);
    if (mode === "vendor" || !hasPkg) {
      changes.push(
        ...copyTree(
          source.webDist,
          `${VENDOR_DIR}/web/dist`,
          root,
          "Vendored Web SDK (offline, reproducible)",
          (f) => !f.endsWith(".tsbuildinfo") && !f.endsWith(".map"),
        ),
      );
      changes.push(...copyTree(join(source.webPackage, "wasm"), `${VENDOR_DIR}/web/wasm`, root, "Vendored WASM core"));
      const vendorPkg = {
        name: "@ultra-motion-x/web",
        version: source.version,
        type: "module",
        main: "./dist/index.js",
        types: "./dist/index.d.ts",
        exports: {
          ".": { types: "./dist/index.d.ts", default: "./dist/index.js" },
          "./wasm": { types: "./dist/wasm/index.d.ts", default: "./dist/wasm/index.js" },
        },
        sideEffects: false,
      };
      add({
        kind: "create",
        path: `${VENDOR_DIR}/web/package.json`,
        description: "Vendored package manifest",
        after: `${JSON.stringify(vendorPkg, null, 2)}\n`,
        before: textFile(`${VENDOR_DIR}/web/package.json`),
      });
      const schema = join(source.root, "docs/schema/config.schema.json");
      if (exists(schema))
        add({
          kind: "create",
          path: `${VENDOR_DIR}/schema/config.schema.json`,
          description: "Config JSON schema",
          after: readFileSync(schema),
          before: null,
        });
    }
    if (hasPkg) {
      const pkg = readJson<Record<string, Record<string, string>>>(join(root, "package.json"))!;
      const value = mode === "vendor" ? `file:${VENDOR_DIR}/web` : `^${source.version}`;
      const previous = pkg.dependencies?.["@ultra-motion-x/web"];
      if (previous !== value) {
        const next = { ...pkg, dependencies: { ...(pkg.dependencies ?? {}), "@ultra-motion-x/web": value } };
        add({
          kind: "json",
          path: "package.json",
          description: `Add dependency @ultra-motion-x/web@${value}`,
          after: `${JSON.stringify(next, null, 2)}\n`,
          before: textFile("package.json"),
          json: { pointer: ["dependencies", "@ultra-motion-x/web"], value, previous },
        });
      }
      manualSteps.push(`Run \`${report.packageManager ?? "npm"} install\` to link the dependency.`);
    }

    const entry = opts.entry ?? report.entryPoints[0];
    const isNext = report.frameworks.some((f) => f.name === "next");
    if (!entry) {
      manualSteps.push("No entry point detected: import `ultra-motion` bootstrap from your client entry manually.");
    } else if (entry.endsWith(".html")) {
      const importPath = hasPkg && mode === "npm" ? "@ultra-motion-x/web" : `./${VENDOR_DIR}/web/dist/index.js`;
      add({
        kind: "create",
        path: "ultra-motion.js",
        description: "Bootstrap (engine + auto-enhance)",
        after: bootstrapSource(defaultConfig(opts.profile ?? "professional", opts.roles), importPath, false),
        before: textFile("ultra-motion.js"),
      });
      const html = textFile(entry)!;
      add({
        kind: "modify",
        path: entry,
        description: "Load the bootstrap module",
        after: injectScript(html, "./ultra-motion.js"),
        before: html,
      });
    } else {
      const ts = /\.tsx?$/.test(entry);
      const dir = dirname(entry);
      const bootName = `ultra-motion.${ts ? "ts" : "js"}`;
      const bootPath = toPosix(join(dir === "." ? "" : dir, bootName));
      add({
        kind: "create",
        path: bootPath,
        description: "Bootstrap (engine + auto-enhance)",
        after: bootstrapSource(defaultConfig(opts.profile ?? "professional", opts.roles), "@ultra-motion-x/web", ts),
        before: textFile(bootPath),
      });
      if (isNext && /layout\.(t|j)sx$/.test(entry)) {
        const client = toPosix(join(dir, `ultra-motion-client.${ts ? "tsx" : "jsx"}`));
        add({
          kind: "create",
          path: client,
          description: "Client component that loads the bootstrap (Next.js)",
          after: `"use client";\nimport { useEffect } from "react";\n\nexport default function UltraMotion() {\n  useEffect(() => {\n    import("./ultra-motion");\n  }, []);\n  return null;\n}\n`,
          before: textFile(client),
        });
        const layout = textFile(entry)!;
        let next = injectImport(layout, "./ultra-motion-client");
        next = next.replace(`import "./ultra-motion-client";`, `import UltraMotion from "./ultra-motion-client";`);
        if (/\{\s*children\s*\}/.test(next) && !next.includes("<UltraMotion />"))
          next = next.replace(/\{\s*children\s*\}/, "<UltraMotion />\n        {children}");
        else manualSteps.push(`Render <UltraMotion /> inside the <body> of ${entry}.`);
        add({
          kind: "modify",
          path: entry,
          description: "Mount the Ultra Motion client component",
          after: next,
          before: layout,
        });
      } else {
        const text = textFile(entry)!;
        add({
          kind: "modify",
          path: entry,
          description: "Import the bootstrap from the entry point",
          after: injectImport(text, `./${basename(bootName, ts ? ".ts" : ".js")}`),
          before: text,
        });
      }
    }

    if (opts.annotate) {
      const targets = [
        ...new Set(
          report.components
            .filter((c) => c.confidence >= 0.7 && ["card", "notification", "drawer", "modal", "menu"].includes(c.role))
            .map((c) => c.file),
        ),
      ];
      for (const f of targets) {
        const before = textFile(f);
        if (!before) continue;
        const { text, count } = annotateSource(before);
        if (count)
          add({
            kind: "modify",
            path: f,
            description: `Annotate ${count} element(s) with data-umx roles`,
            after: text,
            before,
          });
      }
    }
    if (report.platform === "electron")
      notes.push(
        "Electron: optionally use @ultra-motion-x/electron in the main process to expose the display refresh rate and keep animations smooth in background windows.",
      );
    if (adapter !== "web")
      notes.push(
        `Framework adapter available: @ultra-motion-x/${adapter} (hooks/directives for explicit control). Auto-enhance already works framework-agnostically.`,
      );
  } else {
    planNative(report, source, adapter, changes, notes, manualSteps, opts);
  }
  return { root, adapter, mode, version: source.version, changes, notes, manualSteps };
}

const NATIVE: Record<string, { from: string; to: string; note: string }> = {
  unity: {
    from: "platforms/unity",
    to: "Packages/com.ultramotionx.unity",
    note: "Unity package (C# bindings + MonoBehaviour driver).",
  },
  godot: {
    from: "platforms/godot/addons/ultra_motion_x",
    to: "addons/ultra_motion_x",
    note: "Godot 4 (.NET) addon. Enable it in Project Settings → Plugins.",
  },
  flutter: { from: "platforms/mobile/flutter", to: "packages/ultra_motion_x", note: "Dart FFI package." },
  "dotnet-wpf": {
    from: "platforms/windows/dotnet",
    to: "UltraMotionX",
    note: "C# P/Invoke bindings + WPF/WinUI drivers (SDK-style projects compile the copied .cs files automatically).",
  },
  winui: { from: "platforms/windows/dotnet", to: "UltraMotionX", note: "C# P/Invoke bindings + WinUI driver." },
  qt: {
    from: "platforms/desktop/qt",
    to: "third_party/ultra_motion_x",
    note: "Qt adapter (header-only C++ over the C ABI).",
  },
  unreal: { from: "platforms/unreal/UltraMotionX", to: "Plugins/UltraMotionX", note: "Unreal Engine plugin module." },
  "react-native": {
    from: "platforms/mobile/react-native",
    to: `${VENDOR_DIR}/react-native`,
    note: "React Native adapter (JS-driven springs via Animated/setNativeProps).",
  },
};

function planNative(
  report: ProjectReport,
  source: UmxSource,
  adapter: string,
  changes: PlannedChange[],
  notes: string[],
  manual: string[],
  opts: PlanOptions,
): void {
  const n = NATIVE[adapter];
  if (!n) throw new Error(`No installer for adapter \`${adapter}\`.`);
  const root = report.root;
  changes.push(
    ...copyTree(join(source.root, n.from), n.to, root, n.note, (f) => !/node_modules|\.tsbuildinfo$/.test(f)),
  );
  if (adapter !== "react-native") {
    changes.push(
      ...copyTree(join(source.root, "sdk/ffi/include"), toPosix(join(n.to, "include")), root, "C ABI headers"),
    );
    const libs = ["libultra_motion_x.so", "libultra_motion_x.dylib", "ultra_motion_x.dll", "libultra_motion_x.a"];
    const built = libs.map((l) => join(source.root, "target/release", l)).filter((p) => exists(p));
    if (built.length) {
      for (const b of built)
        changes.push({
          kind: "create",
          path: toPosix(join(n.to, "native", basename(b))),
          description: "Native library built from sdk/ffi",
          after: readFileSync(b),
          before: null,
        });
    } else
      manual.push(
        `Build the native library: \`cargo build -p umx-ffi --release\` in ${source.root}, then rerun with --build-native or copy target/release/*ultra_motion_x* into ${n.to}/native.`,
      );
    if (opts.buildNative)
      notes.push("Native library included from target/release (built for the current OS/architecture only).");
  }
  if (adapter === "flutter") {
    const pub = readText(join(root, "pubspec.yaml"));
    if (pub && !pub.includes("ultra_motion_x:")) {
      const next = pub.replace(
        /^dependencies:\s*$/m,
        "dependencies:\n  ultra_motion_x:\n    path: packages/ultra_motion_x",
      );
      if (next !== pub)
        changes.push({
          kind: "modify",
          path: "pubspec.yaml",
          description: "Add ultra_motion_x path dependency",
          after: next,
          before: pub,
        });
      else manual.push("Add `ultra_motion_x: { path: packages/ultra_motion_x }` to pubspec.yaml dependencies.");
    }
  }
  if (adapter === "react-native") {
    // The React Native adapter depends on the framework-agnostic core.
    changes.push(
      ...copyTree(
        source.webDist,
        `${VENDOR_DIR}/web/dist`,
        root,
        "Vendored Web SDK core",
        (f) => !f.endsWith(".tsbuildinfo") && !f.endsWith(".map"),
      ),
    );
    const vp = {
      name: "@ultra-motion-x/web",
      version: source.version,
      type: "module",
      main: "./dist/index.js",
      types: "./dist/index.d.ts",
      sideEffects: false,
    };
    changes.push({
      kind: "create",
      path: `${VENDOR_DIR}/web/package.json`,
      description: "Vendored package manifest",
      after: `${JSON.stringify(vp, null, 2)}\n`,
      before: null,
    });
    const pkg = readJson<Record<string, Record<string, string>>>(join(root, "package.json"));
    if (pkg) {
      const value = `file:${VENDOR_DIR}/react-native`;
      const next = {
        ...pkg,
        dependencies: {
          ...(pkg.dependencies ?? {}),
          "@ultra-motion-x/react-native": value,
          "@ultra-motion-x/web": `file:${VENDOR_DIR}/web`,
        },
      };
      changes.push({
        kind: "json",
        path: "package.json",
        description: "Add @ultra-motion-x/react-native",
        after: `${JSON.stringify(next, null, 2)}\n`,
        before: readText(join(root, "package.json")),
        json: {
          pointer: ["dependencies", "@ultra-motion-x/react-native"],
          value,
          previous: pkg.dependencies?.["@ultra-motion-x/react-native"],
        },
      });
    }
  }
  notes.push(n.note);
}
