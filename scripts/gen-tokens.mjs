#!/usr/bin/env node
// Generates the TypeScript Motion DNA module from presets/profiles.json (single source of
// truth shared with the Rust core). Run with `--check` in CI to verify it is up to date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(readFileSync(join(root, "presets/profiles.json"), "utf8"));
delete src.$comment;
const out = `// GENERATED by scripts/gen-tokens.mjs from presets/profiles.json — do not edit.
import type { ProfilesData } from "./types.ts";

export const PROFILES_DATA: ProfilesData = ${JSON.stringify(src, null, 2)};
`;
const target = join(root, "sdk/typescript/src/tokens/profiles.generated.ts");
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error("profiles.generated.ts is out of date; run `npm run gen:tokens`.");
    process.exit(1);
  }
  console.log("profiles.generated.ts is up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
